/**
 * Deterministic application of approved menu operations (A2).
 *
 * The model only proposes; this module is the single place where an operation
 * list becomes a `MenuDocument`. It is pure (no DB, no HTTP) so it can run
 * both in the chat route (to compute a truthful preview) and in the approval
 * route (to write), and it is tested directly.
 *
 * Rules enforced here, not in the prompt:
 * - only ids that exist in the target document are accepted (the A0 spike
 *   showed the model will occasionally invent a category id),
 * - a price the owner did not state is an error, never a written null,
 * - categories added in the same proposal can be addressed by name, because
 *   their real id is generated by the app,
 * - duplicate operations are collapsed, and repeated updates to one item are
 *   merged so the preview matches what is written,
 * - deletes, publishing and currency changes are not operations at all.
 */

import {
  addCategory,
  addItem,
  moveItemToCategory,
  renameCategory,
  setItemAvailability,
  updateItem,
} from "@/features/menu/menu-utils";
import {
  menuDocumentSchema,
  type MenuCategory,
  type MenuDocument,
  type MenuItem,
} from "@/features/menu/schema";

import {
  ASSISTANT_MAX_OPERATIONS,
  type AddItemOperation,
  type AssistantOperation,
  type ProposalChange,
  type ProposalOperationPreview,
  type ProposalPreview,
  type UpdateItemOperation,
} from "./proposal";

/** Codes are stable for logs/tests; messages are safe to show an owner. */
export type ProposalApplyErrorCode =
  | "no_operations"
  | "too_many_operations"
  | "unknown_item"
  | "unknown_category"
  | "duplicate_category"
  | "missing_price"
  | "empty_update"
  | "invalid_move"
  | "invalid_result";

export class ProposalApplyError extends Error {
  readonly code: ProposalApplyErrorCode;

  constructor(code: ProposalApplyErrorCode, message: string) {
    super(message);
    this.name = "ProposalApplyError";
    this.code = code;
  }
}

export interface AppliedProposal {
  /** The document that would be (or was) written. Never mutated in place. */
  doc: MenuDocument;
  /** Operations after collapsing duplicates, in application order. */
  operations: AssistantOperation[];
  /** Server-computed diff between the input and output documents. */
  preview: ProposalPreview;
}

/* ------------------------------------------------------------------ */
/* Collapsing                                                          */
/* ------------------------------------------------------------------ */

type UpdateOperationPatch = Pick<
  UpdateItemOperation,
  "name" | "description" | "price" | "available" | "dietaryLabels"
>;

function definedPatch(operation: UpdateItemOperation): UpdateOperationPatch {
  const patch: UpdateOperationPatch = {};
  if (operation.name !== undefined) patch.name = operation.name;
  if (operation.description !== undefined) patch.description = operation.description;
  if (operation.price !== undefined) patch.price = operation.price;
  if (operation.available !== undefined) patch.available = operation.available;
  if (operation.dietaryLabels !== undefined) patch.dietaryLabels = [...operation.dietaryLabels];
  return patch;
}

/**
 * Merge repeated updates for one item (later fields win), drop exact duplicate
 * operations, and keep one `add_category` per name. Order is otherwise
 * preserved, because operations like add-then-rename are order-sensitive.
 */
export function collapseOperations(
  operations: readonly AssistantOperation[]
): AssistantOperation[] {
  const result: AssistantOperation[] = [];
  const updateIndex = new Map<string, number>();
  const addedCategoryNames = new Set<string>();
  const seen = new Set<string>();

  for (const operation of operations) {
    if (operation.op === "add_category") {
      const key = operation.name.trim().toLowerCase();
      if (addedCategoryNames.has(key)) continue;
      addedCategoryNames.add(key);
      result.push({ ...operation });
      continue;
    }

    if (operation.op === "update_item") {
      const existingIndex = updateIndex.get(operation.itemId);
      if (existingIndex !== undefined) {
        const existing = result[existingIndex] as UpdateItemOperation;
        result[existingIndex] = { ...existing, ...definedPatch(operation) };
        continue;
      }
      updateIndex.set(operation.itemId, result.length);
      result.push({ ...operation, itemId: operation.itemId });
      continue;
    }

    const fingerprint = JSON.stringify(operation);
    if (seen.has(fingerprint)) continue;
    seen.add(fingerprint);
    result.push({ ...operation });
  }

  return result;
}

/* ------------------------------------------------------------------ */
/* Lookups                                                             */
/* ------------------------------------------------------------------ */

interface FoundItem {
  category: MenuCategory;
  item: MenuItem;
}

function findItem(doc: MenuDocument, itemId: string): FoundItem | null {
  for (const category of doc.categories) {
    const item = category.items.find((candidate) => candidate.id === itemId);
    if (item) return { category, item };
  }
  return null;
}

function findCategory(doc: MenuDocument, categoryId: string): MenuCategory | null {
  return doc.categories.find((category) => category.id === categoryId) ?? null;
}

/**
 * Resolve what the model called a category id. It may be a real id, the exact
 * name of an existing category (case-insensitive), or the name of a category
 * added earlier in this proposal. Anything else is `null`.
 */
function resolveCategoryId(
  doc: MenuDocument,
  reference: string,
  addedCategories: ReadonlyMap<string, string>
): string | null {
  const trimmed = reference.trim();
  if (!trimmed) return null;

  const byId = findCategory(doc, trimmed);
  if (byId) return byId.id;

  const lower = trimmed.toLowerCase();
  const matches = doc.categories.filter((category) => category.name.trim().toLowerCase() === lower);
  if (matches.length === 1) return matches[0].id;
  if (matches.length > 1) return null;

  return addedCategories.get(lower) ?? null;
}

/* ------------------------------------------------------------------ */
/* Formatting (the preview is strings an owner reads)                  */
/* ------------------------------------------------------------------ */

function formatPrice(price: number | null, currency: string | null): string {
  if (price === null) return "no price";
  return currency ? `${price} ${currency}` : String(price);
}

function formatDescription(description: string | null): string {
  return description ?? "no description";
}

function formatAvailability(available: boolean | null): string {
  if (available === true) return "available";
  if (available === false) return "unavailable";
  return "not set";
}

function formatLabels(labels: readonly string[]): string {
  return labels.length > 0 ? labels.join(", ") : "none";
}

function counts(doc: MenuDocument): ProposalPreview["before"] {
  return {
    title: doc.title,
    categories: doc.categories.length,
    items: doc.categories.reduce((total, category) => total + category.items.length, 0),
  };
}

/* ------------------------------------------------------------------ */
/* Preview helpers                                                     */
/* ------------------------------------------------------------------ */

function changesForUpdate(
  before: MenuItem,
  after: MenuItem,
  operation: UpdateItemOperation,
  currency: string | null
): ProposalChange[] {
  const changes: ProposalChange[] = [];

  if (operation.name !== undefined && before.name !== after.name) {
    changes.push({ label: "Name", before: before.name, after: after.name });
  }
  if (operation.price !== undefined && before.price !== after.price) {
    changes.push({
      label: "Price",
      before: formatPrice(before.price, currency),
      after: formatPrice(after.price, currency),
    });
  }
  if (operation.description !== undefined && before.description !== after.description) {
    changes.push({
      label: "Description",
      before: formatDescription(before.description),
      after: formatDescription(after.description),
    });
  }
  if (operation.available !== undefined && before.available !== after.available) {
    changes.push({
      label: "Available",
      before: formatAvailability(before.available),
      after: formatAvailability(after.available),
    });
  }
  if (
    operation.dietaryLabels !== undefined &&
    formatLabels(before.dietaryLabels) !== formatLabels(after.dietaryLabels)
  ) {
    changes.push({
      label: "Dietary labels",
      before: formatLabels(before.dietaryLabels),
      after: formatLabels(after.dietaryLabels),
    });
  }

  return changes;
}

function changesForAdd(operation: AddItemOperation, currency: string | null): ProposalChange[] {
  const changes: ProposalChange[] = [
    { label: "Name", before: null, after: operation.name },
    { label: "Price", before: null, after: formatPrice(operation.price, currency) },
  ];
  if (operation.description !== undefined) {
    changes.push({
      label: "Description",
      before: null,
      after: formatDescription(operation.description),
    });
  }
  if (operation.available !== undefined) {
    changes.push({
      label: "Available",
      before: null,
      after: formatAvailability(operation.available),
    });
  }
  if (operation.dietaryLabels !== undefined) {
    changes.push({
      label: "Dietary labels",
      before: null,
      after: formatLabels(operation.dietaryLabels),
    });
  }
  return changes;
}

