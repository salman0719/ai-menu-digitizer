/* Apply                                                               */
/* ------------------------------------------------------------------ */

/**
 * Apply validated operations to a document. Throws {@link ProposalApplyError}
 * for anything that references data outside this menu; the caller must not
 * write when that happens. The returned document has passed the canonical
 * schema again, so a helper bug cannot persist an invalid menu.
 */
export function applyProposalOperations(
  doc: MenuDocument,
  operations: readonly AssistantOperation[]
): AppliedProposal {
  if (operations.length === 0) {
    throw new ProposalApplyError("no_operations", "There is nothing to apply.");
  }
  if (operations.length > ASSISTANT_MAX_OPERATIONS) {
    throw new ProposalApplyError(
      "too_many_operations",
      `A proposal can change at most ${ASSISTANT_MAX_OPERATIONS} things at once.`
    );
  }

  const collapsed = collapseOperations(operations);
  let next = doc;
  const addedCategories = new Map<string, string>();
  const previewOperations: ProposalOperationPreview[] = [];

  for (const operation of collapsed) {
    switch (operation.op) {
      case "add_category": {
        const name = operation.name.trim();
        const lower = name.toLowerCase();
        const existing = next.categories.some(
          (category) => category.name.trim().toLowerCase() === lower
        );
        if (existing || addedCategories.has(lower)) {
          throw new ProposalApplyError(
            "duplicate_category",
            `The menu already has a category called "${name}".`
          );
        }
        const beforeCount = next.categories.length;
        next = addCategory(next, { name });
        const created = next.categories[next.categories.length - 1];
        if (next.categories.length !== beforeCount + 1 || !created) {
          throw new ProposalApplyError("invalid_result", "The category could not be added.");
        }
        addedCategories.set(lower, created.id);
        previewOperations.push({
          op: "add_category",
          summary: `Add category "${name}"`,
          changes: [{ label: "Category", before: null, after: name }],
        });
        break;
      }

      case "add_item": {
        const categoryId = resolveCategoryId(next, operation.categoryId, addedCategories);
        const category = categoryId ? findCategory(next, categoryId) : null;
        if (!category) {
          throw new ProposalApplyError(
            "unknown_category",
            `I couldn't match "${operation.categoryId}" to a category on this menu.`
          );
        }
        if (operation.price === null) {
          throw new ProposalApplyError(
            "missing_price",
            `What price should "${operation.name}" have?`
          );
        }

        const beforeCount = category.items.length;
        next = addItem(next, category.id, {
          name: operation.name,
          price: operation.price,
          description: operation.description ?? null,
          available: operation.available ?? null,
          dietaryLabels: operation.dietaryLabels,
        });
        const updatedCategory = findCategory(next, category.id);
        const created = updatedCategory?.items[updatedCategory.items.length - 1];
        if (!updatedCategory || updatedCategory.items.length !== beforeCount + 1 || !created) {
          throw new ProposalApplyError("invalid_result", "The item could not be added.");
        }

        previewOperations.push({
          op: "add_item",
          summary: `Add "${created.name}" to "${updatedCategory.name}" — ${formatPrice(
            created.price,
            next.currency
          )}`,
          changes: changesForAdd(operation, next.currency),
        });
        break;
      }

      case "update_item": {
        const found = findItem(next, operation.itemId);
        if (!found) {
          throw new ProposalApplyError(
            "unknown_item",
            `I couldn't match "${operation.itemId}" to an item on this menu.`
          );
        }
        const patch = definedPatch(operation);
        if (Object.keys(patch).length === 0) {
          throw new ProposalApplyError(
            "empty_update",
            "That change does not include anything to update."
          );
        }

        const before = structuredClone(found.item);
        next = updateItem(next, found.category.id, found.item.id, patch);
        const after = findItem(next, operation.itemId)?.item;
        if (!after) {
          throw new ProposalApplyError("invalid_result", "The item could not be updated.");
        }
        previewOperations.push({
          op: "update_item",
          summary: `Update "${after.name}" in "${found.category.name}"`,
          changes: changesForUpdate(before, after, operation, after.currency ?? next.currency),
        });
        break;
      }

      case "set_item_availability": {
        const found = findItem(next, operation.itemId);
        if (!found) {
          throw new ProposalApplyError(
            "unknown_item",
            `I couldn't match "${operation.itemId}" to an item on this menu.`
          );
        }
        next = setItemAvailability(next, found.category.id, found.item.id, operation.available);
        previewOperations.push({
          op: "set_item_availability",
          summary: `Mark "${found.item.name}" ${formatAvailability(operation.available)}`,
          changes: [
            {
              label: "Available",
              before: formatAvailability(found.item.available),
              after: formatAvailability(operation.available),
            },
          ],
        });
        break;
      }

      case "rename_category": {
        const category = findCategory(next, operation.categoryId);
        if (!category) {
          throw new ProposalApplyError(
            "unknown_category",
            `I couldn't match "${operation.categoryId}" to a category on this menu.`
          );
        }
        const name = operation.name.trim();
        const lower = name.toLowerCase();
        const collision = next.categories.some(
          (candidate) =>
            candidate.id !== category.id && candidate.name.trim().toLowerCase() === lower
        );
        if (collision) {
          throw new ProposalApplyError(
            "duplicate_category",
            `The menu already has a category called "${name}".`
          );
        }
        const beforeName = category.name;
        next = renameCategory(next, category.id, name);
        previewOperations.push({
          op: "rename_category",
          summary: `Rename "${beforeName}" to "${name}"`,
          changes: [{ label: "Name", before: beforeName, after: name }],
        });
        break;
      }

      case "move_item": {
        const found = findItem(next, operation.itemId);
        if (!found) {
          throw new ProposalApplyError(
            "unknown_item",
            `I couldn't match "${operation.itemId}" to an item on this menu.`
          );
        }
        const targetId = resolveCategoryId(next, operation.toCategoryId, addedCategories);
        const target = targetId ? findCategory(next, targetId) : null;
        if (!target) {
          throw new ProposalApplyError(
            "unknown_category",
            `I couldn't match "${operation.toCategoryId}" to a category on this menu.`
          );
        }
        if (target.id === found.category.id) {
          throw new ProposalApplyError(
            "invalid_move",
            `"${found.item.name}" is already in "${target.name}".`
          );
        }
        const fromName = found.category.name;
        next = moveItemToCategory(next, found.category.id, target.id, found.item.id);
        previewOperations.push({
          op: "move_item",
          summary: `Move "${found.item.name}" from "${fromName}" to "${target.name}"`,
          changes: [{ label: "Category", before: fromName, after: target.name }],
        });
        break;
      }
    }
  }

  const parsed = menuDocumentSchema.safeParse(next);
  if (!parsed.success) {
    throw new ProposalApplyError(
      "invalid_result",
      "That change would leave the menu in an invalid state, so it was not applied."
    );
  }

  return {
    doc: parsed.data,
    operations: collapsed,
    preview: {
      before: counts(doc),
      after: counts(parsed.data),
      operations: previewOperations,
      warnings: [
        "This changes your draft only — diners see the new version after you publish changes.",
      ],
    },
  };
}
